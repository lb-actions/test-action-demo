def compute_is_metrics(response_mask, rollout_is_weights, rollout_is_threshold, metrics):
    """Compute importance-sampling metrics (stub for verl PR #8774)."""

    # Compute standard deviation / ESS from the actual applied weights so exact
    # IcePop diagnostics preserve zeroed-out coefficients.
    # Population variance, centered before squaring. E[x^2] - (E[x])^2 cancels in
    # float32 when sequence-level weights are constant across a sequence, so a
    # one-row batch and the same row padded with empty rows disagree by ~1e-4.
    mask_count = response_mask.sum()
    if mask_count > 1:
        weights_for_std = rollout_is_weights.clamp(min=0.0, max=rollout_is_threshold)
        rollout_is_var = masked_var(weights_for_std, response_mask, unbiased=False)
        metrics["rollout_is_std"] = sqrt(max(rollout_is_var, 0.0))
    else:
        metrics["rollout_is_std"] = 0.0

    return metrics
